// ---- adversarial round 3 ----------------------------------------------------
//
// The rule both lists are held to: a listing is REFUSED only for a concrete
// datum (a number that reconstructs to a phone, an email, a link, a handle tied
// to an app, an account number beside a bank or wallet word). A phrase with no
// datum is at most HELD for a person — and an ordinary product sentence that
// shares words with one is not even held.

/**
 * Honest lines a person may look at, but that are never refused. Each one is
 * genuinely ambiguous, so a hold is the right outcome — kept short on purpose:
 *
 *   - "Half upfront …, balance on delivery" / "pay 30% upfront to book": an
 *     upfront part-payment is the advance-fee pattern, and checkout takes the
 *     whole price, so a person confirms the deposit goes through checkout;
 *   - "Inbox us for bulk orders": may mean the platform's own messages or an
 *     outside inbox; a person reads which.
 */
